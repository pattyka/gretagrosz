let LANG
try {
  LANG = localStorage.getItem('lang')
} catch {}
if (LANG !== 'de' && LANG !== 'en') LANG = (navigator.languages || [navigator.language]).some((l) => /^de\b/i.test(l)) ? 'de' : 'en'
const t = (s) => (LANG === 'de' && DE[s] != null ? DE[s] : s)

function translatePage() {
  document.documentElement.lang = LANG
  if (LANG === 'de') {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: (n) => (n.parentElement.closest('script, style') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
    })
    const nodes = []
    while (walker.nextNode()) nodes.push(walker.currentNode)
    nodes.forEach((n) => {
      const key = n.nodeValue.replace(/\s+/g, ' ').trim()
      if (key && DE[key] != null) n.nodeValue = n.nodeValue.replace(/\S[\s\S]*\S|\S/, DE[key])
    })
    document.querySelectorAll('[aria-label]').forEach((el) => (el.ariaLabel = t(el.getAttribute('aria-label'))))
    document.querySelectorAll('[data-suffix="bn"]').forEach((el) => (el.dataset.suffix = ' Mrd.'))
    document.title = t(document.title)
  }
  document.querySelectorAll('[data-lang]').forEach((b) => {
    b.classList.toggle('on', b.dataset.lang === LANG)
    b.addEventListener('click', () => {
      try {
        localStorage.setItem('lang', b.dataset.lang)
      } catch {}
      location.reload()
    })
  })
  document.documentElement.classList.remove('i18n-wait')
}
translatePage()
